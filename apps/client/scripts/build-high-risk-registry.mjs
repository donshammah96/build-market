import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const SOURCE_PATH = path.join(
  process.cwd(),
  "app/lib/security/high-risk-registry.ts",
);
const OUTPUT_PATH = path.join(process.cwd(), "scripts/high-risk-registry.mjs");

if (!fs.existsSync(SOURCE_PATH)) {
  console.error(
    "[build-high-risk-registry] Missing source file app/lib/security/high-risk-registry.ts",
  );
  process.exit(1);
}

const source = fs.readFileSync(SOURCE_PATH, "utf8");
const transpileResult = ts.transpileModule(source, {
  fileName: SOURCE_PATH,
  reportDiagnostics: true,
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
    newLine: ts.NewLineKind.LineFeed,
  },
});

const diagnostics = transpileResult.diagnostics ?? [];
const errors = diagnostics.filter(
  (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
);
if (errors.length > 0) {
  console.error("[build-high-risk-registry] Failed to transpile registry:");
  for (const diagnostic of errors) {
    const message = ts.flattenDiagnosticMessageText(
      diagnostic.messageText,
      "\n",
    );
    console.error(`  - ${message}`);
  }
  process.exit(1);
}

const output = [
  "// AUTO-GENERATED FILE. DO NOT EDIT.",
  "// Generated by scripts/build-high-risk-registry.mjs from app/lib/security/high-risk-registry.ts.",
  "",
  transpileResult.outputText.trim(),
  "",
].join("\n");

fs.writeFileSync(OUTPUT_PATH, output, "utf8");
console.log(
  `[build-high-risk-registry] Generated ${path
    .relative(process.cwd(), OUTPUT_PATH)
    .replace(/\\/g, "/")}`,
);
