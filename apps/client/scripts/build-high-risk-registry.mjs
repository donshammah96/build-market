/**
 * build-high-risk-registry.mjs
 *
 * Transpiles app/lib/security/high-risk-registry.ts → scripts/high-risk-registry.mjs
 *
 * TypeScript 7 rewrote the compiler in Go and removed the entire programmatic JS API
 * (transpileModule, ModuleKind, ScriptTarget, etc. are all gone). This script now uses
 * `pnpm exec tsx` — which is already available in the workspace and used by other
 * client scripts — to import the .ts file and serialise its exported constants to JSON
 * via stdout. The parent process then reconstructs a plain ESM file from that JSON.
 *
 * Since high-risk-registry.ts contains only type declarations and plain object-literal
 * constants (no runtime TS-only features), this produces bit-for-bit equivalent output.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SOURCE_PATH = path.join(
  process.cwd(),
  "app/lib/security/high-risk-registry.ts",
);
const OUTPUT_PATH = path.join(process.cwd(), "scripts/high-risk-registry.mjs");

if (!fs.existsSync(SOURCE_PATH)) {
  console.error(
    "[build-high-risk-registry] Missing source file app/lib/security/high-risk-registry.ts",
  );
  process.exit(1);
}

const sourceUrl = pathToFileURL(SOURCE_PATH).href;

// Write a small shim that tsx will execute. It imports the registry and
// prints JSON-serialised exports to stdout, which we capture here.
const shimSource = `
import {
  HIGH_VALUE_SERVER_ACTION_GUARD_RULES,
  HIGH_VALUE_ROUTE_GUARD_RULES,
  CRITICAL_TRANSITION_STEP_SEQUENCE_RULES,
  CRITICAL_VERIFICATION_ADAPTER_STEP_SEQUENCE_RULES,
} from ${JSON.stringify(sourceUrl)};

process.stdout.write(
  JSON.stringify({
    HIGH_VALUE_SERVER_ACTION_GUARD_RULES,
    HIGH_VALUE_ROUTE_GUARD_RULES,
    CRITICAL_TRANSITION_STEP_SEQUENCE_RULES,
    CRITICAL_VERIFICATION_ADAPTER_STEP_SEQUENCE_RULES,
  })
);
`;

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "high-risk-registry-"));
const shimPath = path.join(tmpDir, "shim.mjs");
fs.writeFileSync(shimPath, shimSource, "utf8");

let rawJson;
try {
  // Use `pnpm exec tsx` so tsx is resolved through the workspace, not as a
  // direct dep of apps/client (tsx lives in the workspace root node_modules).
  // execSync with a single string avoids both the DEP0190 warning (shell:true
  // with array args) and the EINVAL issue with pnpm.cmd on Windows.
  const { execSync } = await import("node:child_process");
  rawJson = execSync(`pnpm exec tsx ${JSON.stringify(shimPath)}`, {
    cwd: process.cwd(),
    encoding: "utf8",
  });
} catch (err) {
  console.error("[build-high-risk-registry] Failed to load registry via tsx:");
  console.error(err.stderr ?? err.message);
  process.exit(1);
} finally {
  fs.rmSync(tmpDir, { recursive: true, force: true });
}

let exports;
try {
  exports = JSON.parse(rawJson);
} catch (err) {
  console.error(
    "[build-high-risk-registry] Failed to parse exported registry JSON:",
  );
  console.error(err.message);
  process.exit(1);
}

const {
  HIGH_VALUE_SERVER_ACTION_GUARD_RULES,
  HIGH_VALUE_ROUTE_GUARD_RULES,
  CRITICAL_TRANSITION_STEP_SEQUENCE_RULES,
  CRITICAL_VERIFICATION_ADAPTER_STEP_SEQUENCE_RULES,
} = exports;

const output = [
  "// AUTO-GENERATED FILE. DO NOT EDIT.",
  "// Generated by scripts/build-high-risk-registry.mjs from app/lib/security/high-risk-registry.ts.",
  "",
  `export const HIGH_VALUE_SERVER_ACTION_GUARD_RULES = ${JSON.stringify(HIGH_VALUE_SERVER_ACTION_GUARD_RULES, null, 2)};`,
  "",
  `export const HIGH_VALUE_ROUTE_GUARD_RULES = ${JSON.stringify(HIGH_VALUE_ROUTE_GUARD_RULES, null, 2)};`,
  "",
  `export const CRITICAL_TRANSITION_STEP_SEQUENCE_RULES = ${JSON.stringify(CRITICAL_TRANSITION_STEP_SEQUENCE_RULES, null, 2)};`,
  "",
  `export const CRITICAL_VERIFICATION_ADAPTER_STEP_SEQUENCE_RULES = ${JSON.stringify(CRITICAL_VERIFICATION_ADAPTER_STEP_SEQUENCE_RULES, null, 2)};`,
  "",
].join("\n");

fs.writeFileSync(OUTPUT_PATH, output, "utf8");

console.log(
  `[build-high-risk-registry] Generated ${path
    .relative(process.cwd(), OUTPUT_PATH)
    .replace(/\\/g, "/")}`,
);
